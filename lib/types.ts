/**
 * 회사 "뉴스 재가공 지침"의 결과물(A~G 구조)을 코드로 정의한 파일.
 *
 * 이 파일이 앱 전체의 "약속"입니다.
 * - 화면(components)은 이 모양대로 결과를 그립니다.
 * - 다음 단계에서 Claude API가 이 모양대로 결과를 만들어 보냅니다.
 * 그래서 이 파일만 지켜지면, AI를 붙일 때 화면을 고칠 일이 없습니다.
 */

/* ------------------------------------------------------------------ */
/* 왼쪽 패널 — 사용자가 입력하는 원문 기사 정보                          */
/* ------------------------------------------------------------------ */

export type ArticleInput = {
  /** 기사 주소. 링크로 가져오기를 쓰면 여기에 입력한다. */
  url: string;
  /** 언론사 (예: 재팬코리아데일리) */
  outlet: string;
  /** 기자명 (예: 김주희 기자) */
  reporter: string;
  /** 원문 기사 제목 */
  originalTitle: string;
  /** 게시일 (예: 2026-03-27) */
  publishedAt: string;
  /** 기사 전문(본문). 링크로 가져오면 자동으로 채워진다. */
  bodyText: string;
};

/** 입력 폼의 빈 상태 */
export const EMPTY_INPUT: ArticleInput = {
  url: "",
  outlet: "",
  reporter: "",
  originalTitle: "",
  publishedAt: "",
  bodyText: "",
};

/* ------------------------------------------------------------------ */
/* A. 객관적 사실 목록 (주제별)                                        */
/* ------------------------------------------------------------------ */

export type FactGroup = {
  /** 주제 (예: 일본 사업 구조) */
  topic: string;
  /** 그 주제에 속한 객관적 사실들 */
  facts: string[];
};

/* ------------------------------------------------------------------ */
/* B. 사용에서 제외해야 할 표현과 내용                                  */
/* ------------------------------------------------------------------ */

export type ExcludedItem = {
  /** 원문에서 발견된, 쓰면 안 되는 표현 */
  expression: string;
  /** 왜 제외하는지 (예: 기자의 전망, 직접 인용문, 과장 수식어) */
  reason: string;
};

/* ------------------------------------------------------------------ */
/* C. 회사의 사실 확인이 필요한 항목                                    */
/* ------------------------------------------------------------------ */

export type CheckNeededItem = {
  /** 확인 유형 꼬리표 (예: 사실 확인 필요 / 환율 및 기준일 확인 필요) */
  label: string;
  /** 무엇을 확인해야 하는지 */
  detail: string;
};

/* ------------------------------------------------------------------ */
/* F. 한국어 본문 — "소제목 + 본문" 블록이 여러 개 이어진 구조            */
/* ------------------------------------------------------------------ */

export type BodyBlock = {
  /** 화면에서 블록을 구분하기 위한 고유 번호 */
  id: string;
  /** 소제목 */
  subhead: string;
  /** 본문 문단. 문단을 나눌 때는 줄바꿈(엔터)을 쓴다. */
  paragraphs: string;
  /** 글머리표(필요할 때만). 없으면 빈 배열. */
  bullets: string[];
};

/* ------------------------------------------------------------------ */
/* G. 원문과의 유사성 자체 점검 — 9개 항목                              */
/* ------------------------------------------------------------------ */

/** 각 점검 항목의 판정값. 이 두 가지만 허용된다. */
export type SimilarityVerdict = "적합" | "수정 필요";

export type SimilarityCheckItem = {
  /** 항목 번호 (1~9) */
  no: number;
  /** 점검 항목 이름 */
  label: string;
  /** 판정 */
  verdict: SimilarityVerdict;
  /** 판정 근거 또는 수정 방향 */
  note: string;
};

/* ------------------------------------------------------------------ */
/* A~G 전체를 담는 한국어 원고                                         */
/* ------------------------------------------------------------------ */

export type KoreanDraft = {
  /** A. 객관적 사실 목록 (주제별) */
  factGroups: FactGroup[];
  /** B. 사용에서 제외해야 할 표현과 내용 */
  excluded: ExcludedItem[];
  /** C. 사실 확인이 필요한 항목. 빈 배열이면 "별도 확인 필요 사항 없음"으로 표시된다. */
  needsCheck: CheckNeededItem[];
  /** D. 새로운 한국어 제목 (수정 가능) */
  title: string;
  /** E. 한국어 요약문 (수정 가능) */
  summary: string;
  /** F. 한국어 본문 블록들 (수정 가능) */
  bodyBlocks: BodyBlock[];
  /** F. 출처 안내 문구 */
  sourceNote: string;
  /** F. 환율·수치·날짜 참고 사항. 없으면 빈 배열. */
  references: string[];
  /** G. 원문 유사성 자체 점검 9개 항목 */
  similarityChecks: SimilarityCheckItem[];
};

/* ------------------------------------------------------------------ */
/* 2단계 — 영어 / 일본어 번역본                                        */
/* ------------------------------------------------------------------ */

/** 번역본은 검토용(A~G)이 아니라 배포용이라, 제목·요약·본문 + SEO 구조를 쓴다. */
export type TranslatedDraft = {
  title: string;
  summary: string;
  bodyBlocks: BodyBlock[];
  seoTitle: string;
  metaDescription: string;
  urlSlug: string;
  sourceNote: string;
};

/* ------------------------------------------------------------------ */
/* 화면 상태                                                          */
/* ------------------------------------------------------------------ */

/** 상단 오른쪽 상태칩에 표시되는 진행 단계 */
export type WorkState = "작성 중" | "검토 중" | "승인 완료";

/** 결과 패널의 탭 */
export type LangTab = "ko" | "en" | "ja";
